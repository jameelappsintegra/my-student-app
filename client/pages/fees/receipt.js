import { useEffect, useState } from "react";
import { useRouter } from "next/router";
import Head from "next/head";
import { ErrorState, Loading } from "../../components/common";
import { api } from "../../services/api";
import { PAYMENT_METHODS, classLabel, formatDate, money } from "../../constants";

// Printable receipt for one fee payment.
export default function Receipt() {
  const router = useRouter();
  const { student, invoice, payment } = router.query;
  const [state, setState] = useState({ loading: true });
  useEffect(() => {
    if (!student || !invoice || !payment) return;
    api.students.receipt(student, invoice, payment).then((r) => setState({ data: r.data })).catch((error) => setState({ error }));
  }, [student, invoice, payment]);
  if (state.loading) return <Loading />;
  if (state.error) return <div className="p-4"><ErrorState error={state.error} /></div>;
  const r = state.data;
  const m = (n) => money(n, r.currency, r.locale);
  const rows = [
    ["Received from", `${r.student.father ? `${r.student.father} for ` : ""}${r.student.name}`],
    ["Admission no.", r.student.admissionNumber],
    ["Class", `${classLabel(r.student.className)}${r.student.section ? ` ${r.student.section}` : ""}`],
    ["Towards", `${r.invoice.title} (${r.invoice.academicYear})`],
    ["Paid by", `${PAYMENT_METHODS[r.method] || r.method}${r.reference ? ` · ref ${r.reference}` : ""}`],
    ["Bill amount", m(r.invoice.amount)],
    ["Balance after this payment", r.invoice.balanceAfter ? m(r.invoice.balanceAfter) : "Nil (fully paid)"],
  ];
  return (
    <div className="min-h-screen bg-slate-100 print:bg-white py-6 px-4">
      <Head><title>{`Receipt ${r.receiptNumber}`}</title></Head>
      <div className="max-w-xl mx-auto flex gap-2 mb-4 print:hidden">
        <button className="btn btn-sm" onClick={() => router.back()}>‹ Back</button>
        <button className="btn btn-sm btn-primary" onClick={() => window.print()}>Print or save as PDF</button>
      </div>
      <article className="max-w-xl mx-auto bg-white border border-slate-300 print:border-0 rounded-lg p-6 sm:p-10">
        <header className="text-center border-b-2 border-slate-800 pb-3 mb-5">
          <h1 className="text-xl font-bold uppercase tracking-wide">{r.school.name}</h1>
          <p className="text-xs text-slate-600">{[r.school.address, r.school.city].filter(Boolean).join(", ")}</p>
          <p className="text-xs text-slate-500">{[r.school.phone, r.school.email].filter(Boolean).join(" · ")}</p>
        </header>
        <div className="flex justify-between items-baseline mb-5">
          <h2 className="text-lg font-semibold">Fee receipt</h2>
          <div className="text-right text-sm"><p>No. <strong className="font-mono">{r.receiptNumber}</strong></p><p>Date: {formatDate(r.paidAt)}</p></div>
        </div>
        <p className="text-center text-3xl font-bold tabular-nums my-6">{r.amountText}</p>
        <dl className="text-sm divide-y divide-slate-100">
          {rows.map(([k, v]) => <div key={k} className="flex justify-between gap-4 py-2"><dt className="text-slate-500">{k}</dt><dd className="text-right font-medium">{v}</dd></div>)}
        </dl>
        <footer className="mt-12 flex justify-between items-end text-xs text-slate-500">
          <p>This receipt is generated by the school&apos;s records system.</p>
          <p className="border-t border-slate-400 pt-1 px-4 text-center">Accounts office</p>
        </footer>
      </article>
    </div>
  );
}
